package org.commands;

/**
 * Команда вывода справки по доступным серверным командам.
 */
public class ServerHelpCommand extends ServerCommand {

    /**
     * Выводит справку по доступным серверным командам.
     *
     * @param context серверный контекст
     * @return строка со справкой
     */
    @Override
    public String exec(ServerContext context) {
        return """
        help : вывести справку по доступным серверным консольным командам
        info : вывести информацию о всей коллекции на сервере
        show : вывести все элементы коллекции на сервере
        insert key {element} : добавить новый элемент с заданным ключом от имени сервера
        update id {element} : обновить элемент коллекции по id от имени сервера
        remove_key key : удалить элемент из коллекции по ключу
        clear : очистить коллекцию от элементов, принадлежащих серверу
        exit : завершить сервер
        replace_if_lower key {element} : заменить значение по ключу, если новое значение меньше старого
        remove_greater_key null : удалить из коллекции все элементы, ключ которых превышает заданный
        remove_lower_key null : удалить из коллекции все элементы, ключ которых меньше, чем заданный
        filter_by_genre genre : вывести элементы, значение поля genre которых равно заданному
        filter_contains_name name : вывести элементы, значение поля name которых содержит заданную подстроку
        filter_less_than_mpaa_rating mpaaRating : вывести элементы, значение поля mpaaRating которых меньше заданного

        Серверная консоль выполняет команды локально, не требует login/register и не подключается к другим серверам.
        """;
    }
}
