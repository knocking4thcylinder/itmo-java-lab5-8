package org.commands;

/**
 * Команда вывода справки по доступным клиентским командам.
 */
class HelpCommand extends ClientCommand {

    /**
     * Выводит справку по доступным командам.
     * @param context клиентский контекст
     * @return строка со справкой
     */
    @Override
    public String exec(ClientContext context) {
        return """
        register login password : зарегистрироваться на сервере и войти
        login login password : войти на сервер
        help : вывести справку по доступным клиентским командам
        info : вывести информацию о принадлежащей текущему пользователю части коллекции
        show : вывести все элементы, принадлежащие текущему пользователю
        insert key {element} : добавить новый элемент с заданным ключом
        update id {element} : обновить принадлежащий текущему пользователю элемент по id
        remove_key key : удалить принадлежащий текущему пользователю элемент по ключу
        clear : удалить все элементы текущего пользователя
        execute_script file_name : считать и исполнить скрипт из указанного файла
        exit : завершить клиент
        replace_if_lower key {element} : заменить принадлежащий текущему пользователю элемент, если новое значение меньше старого
        remove_greater_key key : удалить элементы текущего пользователя, ключ которых превышает заданный
        remove_lower_key key : удалить элементы текущего пользователя, ключ которых меньше заданного
        filter_by_genre genre : вывести элементы текущего пользователя с заданным genre
        filter_contains_name name : вывести элементы текущего пользователя, имя которых содержит подстроку
        filter_less_than_mpaa_rating mpaaRating : вывести элементы текущего пользователя с mpaaRating меньше заданного

        Все серверные команды, кроме register и login, требуют входа.
        """;
    }
}
